"""Writes README.md from content.py so links and alt text never drift from the graphics."""

import os
import re
from urllib.parse import urlparse

from content import ARCHIVE, BUTTONS, FEATURED, PROFILE, SECTIONS, TERMINAL

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SNAKE = "https://raw.githubusercontent.com/Arrow-Ghost/Arrow-Ghost/output/snake.svg"


def slug(s):
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]", "-", s.lower())).strip("-")


def attr(s):
    return s.replace("&", "&amp;").replace('"', "&quot;")


def img(src, alt, width="100%", height=None):
    size = f'height="{height}"' if height else f'width="{width}"'
    return f'<img src="./assets/{src}" {size} alt="{attr(alt)}"/>'


def chapter(i):
    num, title, sub = SECTIONS[i]
    return f'<p align="center">{img(f"h-{num}.svg", f"Chapter {num}: {title.title()}. {sub}")}</p>'


def main():
    out = []
    out.append("<!--\n  ARROW—GHOST · the profile of Shrish Verma\n"
               "  Every graphic on this page is a hand-generated, self-contained SVG — see /scripts.\n"
               "  No third-party stat cards. Telemetry refreshes itself via GitHub Actions.\n"
               "  If you're reading the source: hi. Respect.\n-->\n")

    out.append(f'<p align="center">\n  {img("hero.svg", "SHRISH VERMA — Arrow-Ghost. Building at the edge of cybersecurity, quantum computing, AI, embedded & IoT and full-stack web. B.Tech CSE at VIT Vellore, IEEE Junior Core, web developer for IEEE ITC India 2026.")}\n</p>\n')

    btns = []
    for key, label, url in BUTTONS:
        alt = {"linkedin": "LinkedIn", "email": "Email", "play": "Play Quantum Maze (live)"}.get(key, label.title())
        btns.append(f'  <a href="{attr(url)}">{img(f"btn-{key}.svg", alt, height=42)}</a>')
    out.append('<p align="center">\n' + "\n  &nbsp;\n".join(btns) + "\n</p>\n")

    # 01 — who am i
    out.append(chapter(0))
    whoami_alt = " ".join(re.sub(r"\s{2,}|\.{3,}", " ", l.removeprefix("$ ")) for l in TERMINAL if l.strip() not in ("", "$"))
    out.append(f'<p align="center">{img("whoami.svg", whoami_alt)}</p>\n')

    # 02 — arsenal
    out.append(chapter(1))
    out.append(f'<p align="center">{img("arsenal.svg", "Arsenal: Python, TypeScript, JavaScript, C, C++, Java, Go, Dart, GLSL; React, Next.js, Astro, Node.js, Express, FastAPI, Flask, Three.js, WebGL2; Gemini Live, YOLOv8, OpenVINO, ONNX Runtime, OpenCV, Whisper; Qiskit; Kali Linux, Nmap, Burp Suite, Wireshark, Metasploit; Arduino, ESP32, Raspberry Pi 5, KiCad; MongoDB Atlas, PostgreSQL, Supabase, Firebase, Docker, Vercel; Flutter, Kotlin, Figma.")}</p>\n')

    # 03 — featured operations
    out.append(chapter(2))
    for p in FEATURED:
        target = p["live"] or p["repo"]
        alt = f'{p["code"]} {p["title"]} — {p["tagline"]} {p["desc"]} Stack: {", ".join(p["stack"])}.'
        out.append(f'<p align="center"><a href="{target}">{img("op-" + p["key"] + ".svg", alt)}</a></p>')
        links = []
        if p["live"]:
            links.append(f'<a href="{p["live"]}"><b>▶ live</b> · {urlparse(p["live"]).netloc}</a>')
        links.append(f'<a href="{p["repo"]}"><b>◆ source</b> · {p["repo"].replace("https://github.com/", "")}</a>')
        out.append('<p align="center"><sub>' + " &nbsp;&nbsp;│&nbsp;&nbsp; ".join(links) + "</sub></p>\n")

    # 04 — archive (2 per row)
    out.append(chapter(3))
    for i in range(0, len(ARCHIVE), 2):
        row = []
        for a in ARCHIVE[i:i + 2]:
            row.append(f'  <a href="{a["live"] or a["repo"]}">{img("arc-" + slug(a["title"]) + ".svg", a["title"] + " — " + a["line"], width="49%")}</a>')
        out.append('<p align="center">\n' + "\n".join(row) + "\n</p>")
    out.append("")

    # 05 — mission log
    out.append(chapter(4))
    out.append(f'<p align="center">{img("mission-log.svg", "Mission log: web developer for the 10th IEEE International Test Conference India 2026; IEEE Junior Core Member at VIT Vellore; Smart India Hackathon 2025 internal finalist; All India Rank 1 in the National AI Idea-thon by 1M1B; podium at IIT Delhi Code Day hackathon; President of Cyber Genie, ranked the #1 club three years running; writing a research paper and a book on quantum computing game development.")}</p>\n')

    # 06 — telemetry
    out.append(chapter(5))
    out.append(f'<p align="center">{img("telemetry.svg", "Live GitHub telemetry: contributions, streaks and the contribution calendar.")}</p>')
    out.append(f'<p align="center">{img("langs.svg", "Language spectrum by bytes of code.")}</p>')
    out.append(f'<p align="center"><img src="{SNAKE}" width="100%" alt="A snake eating the contribution graph."/></p>\n')

    # credits
    out.append(f'<p align="center">{img("credits.svg", "Closing credits. Directed by Shrish Verma. To be continued.")}</p>\n')
    out.append('<p align="center"><sub>every pixel above is a hand-built SVG generated by <a href="./scripts">/scripts</a> · '
               'fonts: Source Sans / Source Code (SIL OFL)</sub></p>\n')

    with open(os.path.join(ROOT, "README.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print("  wrote README.md")


if __name__ == "__main__":
    main()

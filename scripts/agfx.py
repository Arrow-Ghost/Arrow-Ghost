"""agfx — tiny SVG toolkit for the Arrow-Ghost profile.

Every graphic in this repo is generated by a script that imports this module.
GitHub serves README images through a proxy as <img>, so each SVG must be fully
self-contained: no scripts, no external fonts, no external images. agfx handles
that by embedding a per-file subset of the fonts that file actually uses (WOFF,
base64) and by turning display type into plain vector paths.

Fonts: Source Sans Pro / Source Code Pro (SIL Open Font License 1.1, see
scripts/fonts/OFL-*.txt). Embedded subsets are renamed "AG Sans" / "AG Mono".
"""

